"""Emit reproducibility bundle: commands.sh, environment.yml, checksums.sha256."""
from __future__ import annotations

import shutil
from pathlib import Path

from clawbio.workflow import state as st


HEADER = "#!/usr/bin/env bash\n# Generated by clawbio-flow bundle. Do not edit by hand.\nset -euo pipefail\n"


def cmd_bundle() -> None:
    state = st.read()
    run = st.run_dir()

    not_done = [
        sid for sid, e in state["steps"].items() if e["status"] not in (st.DONE, st.SKIPPED)
    ]
    if not_done:
        raise RuntimeError(
            f"cannot bundle: steps not done: {not_done}"
        )

    _write_commands_sh(state, run / "commands.sh")
    _write_checksums(state, run / "checksums.sha256")
    _write_environment_yml(state, run / "environment.yml")

    state["bundled_at"] = st.now_iso()
    st.append_event(state, "bundle")
    st.write(state)
    print(f"bundle written to {run}/ (commands.sh, checksums.sha256, environment.yml)")


def _write_commands_sh(state: dict, path: Path) -> None:
    lines = [HEADER]
    lines.append(f"# skill: {state['skill']}\n\n")
    for event in state["events"]:
        if event["kind"] == "done":
            step_entry = state["steps"][event["step"]]
            lines.append(f"# step: {event['step']}\n")
            lines.append(step_entry["command"] + "\n\n")

    skipped = [(sid, e) for sid, e in state["steps"].items() if e["status"] == st.SKIPPED]
    if skipped:
        lines.append("# --- skipped steps (not executed) ---\n")
        for sid, entry in skipped:
            lines.append(f"# skipped: {sid} (reason: {entry.get('skip_reason') or 'no reason given'})\n")

    path.write_text("".join(lines))
    path.chmod(0o755)


def _write_checksums(state: dict, path: Path) -> None:
    """Standard two-column digest+path format; comments on preceding lines.

    The two-column form is what `sha256sum -c` / `shasum -a 256 -c` parse — any
    trailing text on the data line is treated as part of the filename.
    """
    lines = []
    for sid, entry in state["steps"].items():
        for key, h in entry["output_hashes"].items():
            digest = h.split(":", 1)[-1]
            output_path = entry["outputs"][key]
            lines.append(f"# step={sid} key={key}\n")
            lines.append(f"{digest}  {output_path}\n")
    path.write_text("".join(lines))


def _write_environment_yml(state: dict, path: Path) -> None:
    skill_env = Path(state["skill_dir"]) / "environment.yml"
    if skill_env.is_file():
        shutil.copy2(skill_env, path)
        return
    path.write_text(
        f"# Generated by clawbio-flow bundle for skill {state['skill']!r}.\n"
        "# No environment.yml found in skill directory; this is a placeholder.\n"
        "name: clawbio-run\n"
        "channels: []\n"
        "dependencies: []\n"
    )
