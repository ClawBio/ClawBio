#!/usr/bin/env python3
"""Render a unified Markdown report from merged.json."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def fmt_maf(v) -> str:
    if v is None:
        return "—"
    try:
        return f"{float(v):.4f}"
    except (TypeError, ValueError):
        return str(v)


def render(merged: dict) -> str:
    variant = merged.get("variant", {})
    rsid = merged.get("rsid", "?")
    sources = merged.get("sources", {})
    summary = merged.get("summary", {})

    lines: list[str] = []
    lines.append(f"# GWAS Lookup — {rsid}")
    lines.append("")
    lines.append("## Variant")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    lines.append(f"| rsID | `{rsid}` |")
    lines.append(f"| Position (GRCh38) | `{variant.get('chr', '?')}:{variant.get('pos_grch38', '?')}` |")
    lines.append(f"| Position (GRCh37) | `{variant.get('chr', '?')}:{variant.get('pos_grch37', '?')}` |")
    lines.append(f"| Alleles | `{variant.get('allele_string', '?')}` |")
    lines.append(f"| Variant class | {variant.get('var_class', '—')} |")
    lines.append(f"| Most severe consequence | `{variant.get('most_severe_consequence', '—')}` |")
    lines.append(f"| Minor allele | `{variant.get('minor_allele', '—')}` (MAF {fmt_maf(variant.get('maf'))}) |")
    lines.append("")

    pops = variant.get("populations", []) or []
    if pops:
        lines.append("### Population frequencies")
        lines.append("")
        lines.append("| Population | Allele | Frequency |")
        lines.append("|---|---|---|")
        for p in pops[:12]:
            lines.append(f"| {p.get('population', '—')} | `{p.get('allele', '—')}` | {fmt_maf(p.get('frequency'))} |")
        lines.append("")

    lines.append("## Sources")
    lines.append("")
    lines.append(f"Queried {summary.get('total_sources', '?')} sources; {summary.get('ok_sources', '?')} returned data.")
    lines.append("")
    lines.append("| Source | Status |")
    lines.append("|---|---|")
    for src, status in (summary.get("statuses") or {}).items():
        lines.append(f"| `{src}` | {status} |")
    lines.append("")

    gwas = sources.get("gwas_catalog", {})
    if gwas.get("status") == "ok":
        lines.append("### GWAS Catalog associations")
        lines.append("")
        assocs = gwas.get("associations") or gwas.get("raw") or []
        if assocs:
            lines.append(f"Total: **{gwas.get('total_associations', len(assocs))}** associations.")
            lines.append("")
            lines.append("| Traits | p-value | Risk allele | OR/Beta | Study |")
            lines.append("|---|---|---|---|---|")
            for a in assocs[:10]:
                traits = ", ".join(a.get("traits", [])) if isinstance(a.get("traits"), list) else (a.get("trait") or "")
                pval = a.get("pvalue") or a.get("pValue") or "—"
                risk = a.get("risk_allele") or "—"
                or_beta = a.get("or_beta") or a.get("beta_num") or "—"
                study = a.get("study_accession") or a.get("study") or "—"
                lines.append(f"| {traits or '—'} | {pval} | `{risk}` | {or_beta} | `{study}` |")
            lines.append("")

    for src_name, label in [
        ("open_targets", "Open Targets Genetics"),
        ("open_targets_credsets", "Open Targets credible sets"),
        ("pheweb_ukb", "UKB-TOPMed PheWeb"),
        ("finngen", "FinnGen r12"),
        ("pheweb_bbj", "Biobank Japan PheWeb"),
        ("gtex", "GTEx v8 eQTLs"),
        ("eqtl_catalogue", "EBI eQTL Catalogue"),
    ]:
        s = sources.get(src_name, {})
        status = s.get("status", "?")
        if status != "ok":
            continue
        lines.append(f"### {label}")
        lines.append("")
        lines.append("```json")
        compact = {k: v for k, v in s.items() if k not in ("rsid",)}
        text = json.dumps(compact, indent=2)
        if len(text) > 2000:
            text = text[:2000] + "\n... (truncated)"
        lines.append(text)
        lines.append("```")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("_Generated by ClawBio 2.0 `gwas_lookup` skill. Data may be cached fixtures (offline demo mode)._")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--merged", required=True, type=Path)
    p.add_argument("--out", required=True, type=Path)
    args = p.parse_args()

    merged = json.loads(args.merged.read_text())
    text = render(merged)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"[report] wrote {args.out} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
