"""Output contract for scores withheld by the ``--min-overlap`` gate.

A score whose variant overlap falls below ``--min-overlap`` is not calculated.
That decision used to reach stdout only: the score was absent from every output
file, and a run in which no score cleared the gate exited 0 having written
nothing at all, so a caller could not tell an abstention from a run that never
happened. clawbio_bench's gwas-prs harness reads ``prs_results.json`` in
exactly that case and graded the three low-coverage cases ``missing_output``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path

import pytest
from hypothesis import given, settings
from hypothesis import strategies as st

SKILL_DIR = Path(__file__).resolve().parents[1]
PANEL_ID = "CLAWBIO-T2D-8"
DISCLAIMER_START = "ClawBio is a research and educational tool"
DOCUMENTED_OUTPUTS = {
    "prs_report.md",
    "prs_results.json",
    "prs_variants.csv",
    "result.json",
    "reproducibility/commands.sh",
    "reproducibility/environment.yml",
    "reproducibility/provenance.json",
    "reproducibility/checksums.sha256",
}


def _load_module(name: str, path: Path):
    spec = spec_from_file_location(name, path)
    module = module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


ENGINE = _load_module("gwas_prs_skipped_scores", SKILL_DIR / "gwas_prs.py")
PANEL_VARIANTS = ENGINE.parse_scoring_file(ENGINE.curated_panel_path(PANEL_ID))


def _genotype_file(path: Path, n_matching: int) -> Path:
    """A 23andMe-style file carrying the first ``n_matching`` panel variants."""
    lines = [
        "# This data file generated by 23andMe at: Mon Jan  1 00:00:00 2024",
        "#",
        "# rsid\tchromosome\tposition\tgenotype",
    ]
    for variant in PANEL_VARIANTS[:n_matching]:
        allele = variant["effect_allele"]
        lines.append(f"{variant['rsid']}\t1\t1000\t{allele}{allele}")
    # unrelated markers, so the file is never empty
    lines += [f"rs99999{i:02d}\t1\t{2000 + i}\tAG" for i in range(5)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _run_cli(
    input_path: Path, output_dir: Path | None, *args: str
) -> subprocess.CompletedProcess[str]:
    cmd = [
        sys.executable,
        str(SKILL_DIR / "gwas_prs.py"),
        "--input",
        str(input_path),
        "--panel-id",
        PANEL_ID,
        "--cache-dir",
        str(input_path.parent / "pgs_cache"),
        *args,
    ]
    if output_dir is not None:
        cmd += ["--output", str(output_dir)]
    return subprocess.run(cmd, capture_output=True, text=True, timeout=120)


def _files(output_dir: Path) -> set[str]:
    return {
        path.relative_to(output_dir).as_posix()
        for path in output_dir.rglob("*")
        if path.is_file()
    }


class TestNoScoreCalculated:
    """Every requested score fell below ``--min-overlap``."""

    @pytest.mark.parametrize("n_matching", [0, 1, 3])
    def test_run_writes_the_documented_outputs_and_an_empty_result_list(
        self, tmp_path, n_matching
    ):
        out = tmp_path / "out"
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", n_matching), out)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        assert _files(out) == DOCUMENTED_OUTPUTS
        # the list a consumer indexes by score: valid JSON, and no entry for a
        # score that was not calculated
        assert json.loads((out / "prs_results.json").read_text()) == []

    def test_envelope_names_the_skipped_score_and_why(self, tmp_path):
        out = tmp_path / "out"
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", 3), out)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        envelope = json.loads((out / "result.json").read_text())
        summary = envelope["summary"]
        assert summary["scores_calculated"] == 0
        assert summary["scores_skipped"] == 1
        # no calculated score, so nothing in the summary describes one: a false
        # curated_demo_panel here would read as "this was a PGS Catalog score"
        for key in (
            "score_id",
            "raw_score",
            "percentile",
            "risk_category",
            "curated_demo_panel",
            "legacy_pgs_compatibility",
        ):
            assert summary[key] is None, key
        assert envelope["data"]["results"] == []
        (skipped,) = envelope["data"]["skipped_scores"]
        assert skipped["score_id"] == PANEL_ID
        assert skipped["reason"] == "overlap_below_min_overlap"
        assert (skipped["variants_used"], skipped["variants_total"]) == (3, 8)
        assert skipped["overlap_fraction"] == pytest.approx(0.375)
        assert skipped["min_overlap"] == pytest.approx(0.5)
        # issue #356: a curated panel must not read as a PGS Catalog score here either
        assert skipped["curated_demo_panel"] is True
        assert skipped["pgs_id"] is None

    def test_report_states_that_nothing_was_scored(self, tmp_path):
        out = tmp_path / "out"
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", 3), out)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        report = (out / "prs_report.md").read_text()
        assert "No polygenic risk score was calculated" in report
        assert PANEL_ID in report and "3/8" in report and "37.5%" in report
        assert "--min-overlap" in report and "50%" in report
        assert "NOT a PGS Catalog score" in report
        assert DISCLAIMER_START in report
        # nothing that could be read as a result
        for heading in ("## Score Details", "Risk Category", "Percentile"):
            assert heading not in report, heading

    def test_variant_table_has_a_header_and_no_rows(self, tmp_path):
        out = tmp_path / "out"
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", 3), out)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        lines = (out / "prs_variants.csv").read_text().splitlines()
        assert lines == [
            "score_id,rsid,effect_allele,genotype,dosage,weight,contribution,status"
        ]

    def test_provenance_records_the_panel_that_was_evaluated(self, tmp_path):
        out = tmp_path / "out"
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", 3), out)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        provenance = json.loads((out / "reproducibility/provenance.json").read_text())
        (scoring_file,) = provenance["scoring_files"]
        assert scoring_file["score_id"] == PANEL_ID
        assert scoring_file["sha256"]

    def test_lowering_min_overlap_scores_the_same_input(self, tmp_path):
        # the gate, not the input, is what withheld the score
        out = tmp_path / "out"
        proc = _run_cli(
            _genotype_file(tmp_path / "in.txt", 3), out, "--min-overlap", "0.3"
        )
        assert proc.returncode == 0, proc.stdout + proc.stderr
        (result,) = json.loads((out / "prs_results.json").read_text())
        assert (result["variants_used"], result["variants_total"]) == (3, 8)
        envelope = json.loads((out / "result.json").read_text())
        assert envelope["summary"]["scores_skipped"] == 0
        assert envelope["data"]["skipped_scores"] == []

    def test_without_output_dir_the_run_still_exits_zero_and_says_why(self, tmp_path):
        proc = _run_cli(_genotype_file(tmp_path / "in.txt", 3), None)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        assert "below --min-overlap" in proc.stdout
        assert "No polygenic risk score was calculated" in proc.stdout


class TestSomeScoresSkipped:
    """One score calculated, the rest withheld: the skip must be on record."""

    @pytest.fixture()
    def partial_run(self, tmp_path, monkeypatch):
        # --demo is the only offline path that scores several panels. Point it
        # at a patient who carries the T2D panel's variants and no others.
        fake_skill_dir = tmp_path / "skill"
        fake_skill_dir.mkdir()
        _genotype_file(fake_skill_dir / "demo_patient_prs.txt", len(PANEL_VARIANTS))
        monkeypatch.setattr(ENGINE, "SKILL_DIR", fake_skill_dir)
        out = tmp_path / "out"
        argv = ["gwas_prs.py", "--demo", "--output", str(out)]
        argv += ["--cache-dir", str(tmp_path / "pgs_cache")]
        monkeypatch.setattr(sys, "argv", argv)
        ENGINE.main()
        return out

    def test_scored_panel_is_reported_and_skipped_panels_are_listed(self, partial_run):
        results = json.loads((partial_run / "prs_results.json").read_text())
        assert [r["score_id"] for r in results] == [PANEL_ID]
        envelope = json.loads((partial_run / "result.json").read_text())
        assert envelope["summary"]["scores_calculated"] == 1
        skipped = envelope["data"]["skipped_scores"]
        assert envelope["summary"]["scores_skipped"] == len(skipped) == 5
        assert {s["score_id"] for s in skipped} == set(ENGINE.CURATED_SCORES) - {
            PANEL_ID
        }
        assert all(s["reason"] == "overlap_below_min_overlap" for s in skipped)

    def test_report_lists_the_skipped_panels_beside_the_result(self, partial_run):
        report = (partial_run / "prs_report.md").read_text()
        assert "## Score Details" in report
        section = report.split("## Scores Not Calculated", 1)[1].split("\n## ", 1)[0]
        for panel_id in set(ENGINE.CURATED_SCORES) - {PANEL_ID}:
            assert panel_id in section, panel_id
        assert PANEL_ID not in section

    def test_provenance_records_every_evaluated_panel(self, partial_run):
        provenance = json.loads(
            (partial_run / "reproducibility/provenance.json").read_text()
        )
        assert {s["score_id"] for s in provenance["scoring_files"]} == set(
            ENGINE.CURATED_SCORES
        )


def test_report_without_skipped_scores_has_no_such_section():
    results = [
        {
            "score_id": PANEL_ID,
            "pgs_id": None,
            "trait": "Type 2 diabetes",
            "prs": {
                "raw_score": 0.57,
                "variants_used": 7,
                "variants_total": 8,
                "variants_missing": 1,
                "overlap_fraction": 0.875,
                "per_variant": [],
            },
            "percentile_info": {
                "percentile": 88.5,
                "method": "curated_reference",
                "risk_category": "Elevated",
                "z_score": 1.2,
                "reference_population": "EUR",
            },
            "metadata": {},
        }
    ]
    info = {"filepath": "p.txt", "format": "23andme", "total_snps": 10}
    report = ENGINE.generate_report(results, info, argparse.Namespace(build="GRCh37"))
    assert "Scores Not Calculated" not in report


@settings(max_examples=40, deadline=None)
@given(
    n_matching=st.integers(0, len(PANEL_VARIANTS)),
    min_overlap=st.floats(0.0, 1.0, allow_nan=False),
)
def test_a_score_is_either_reported_or_recorded_as_skipped(n_matching, min_overlap):
    """Whatever the overlap and the bar, no requested score goes missing."""
    genotypes = {v["rsid"]: v["effect_allele"] * 2 for v in PANEL_VARIANTS[:n_matching]}
    prs = ENGINE.calculate_prs(genotypes, PANEL_VARIANTS)
    skipped = ENGINE.skipped_score_record(
        {"score_id": PANEL_ID, "pgs_id": None, "trait": "Type 2 diabetes"},
        prs,
        min_overlap,
    )
    below = n_matching / len(PANEL_VARIANTS) < min_overlap
    assert (skipped is not None) == below
    if skipped is not None:
        assert skipped["variants_used"] == n_matching
        assert skipped["overlap_fraction"] < skipped["min_overlap"]
