import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))
from vcf_annotator import parse_vcf


# ── Helpers ────────────────────────────────────────────────────────────────────

def write_tmp(content: str, suffix: str = ".vcf") -> Path:
    """Write content to a temp file and return its Path."""
    tmp = tempfile.NamedTemporaryFile(
        mode="w", suffix=suffix, delete=False, encoding="utf-8"
    )
    tmp.write(content)
    tmp.flush()
    return Path(tmp.name)


VALID_VCF = """\
##fileformat=VCFv4.2
##reference=GRCh38
#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO
17\t43044295\trs80357382\tG\tA\t.\tPASS\t.
13\t32316461\trs80359550\tC\tT\t.\tPASS\t.
"""

EMPTY_FILE = ""

NO_CHROM_HEADER = """\
##fileformat=VCFv4.2
17\t43044295\trs80357382\tG\tA\t.\tPASS\t.
"""

SPACE_DELIMITED = """\
##fileformat=VCFv4.2
#CHROM POS ID REF ALT QUAL FILTER INFO
17 43044295 rs80357382 G A . PASS .
"""

HEADER_ONLY = """\
##fileformat=VCFv4.2
##reference=GRCh38
#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO
"""

NON_VCF_CONTENT = """\
# Demo query
# This is NOT a VCF file
BRCA1 breast cancer
rs80357382
"""

TWENTY_THREE_AND_ME_LIKE = """\
# This data file generated by 23andMe
# rsid\tchromosome\tposition\tgenotype
rs4477212\t1\t82154\tAA
rs3094315\t1\t752566\tAA
"""


# ── Tests: invalid input should exit non-zero ──────────────────────────────────

class TestInvalidVCFInputExitsNonZero:

    def test_empty_file_exits_nonzero(self):
        p = write_tmp(EMPTY_FILE)
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_no_chrom_header_exits_nonzero(self):
        p = write_tmp(NO_CHROM_HEADER)
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_space_delimited_exits_nonzero(self):
        """Space-delimited VCF should exit non-zero (tabs required)."""
        p = write_tmp(SPACE_DELIMITED)
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_header_only_no_variants_exits_nonzero(self):
        """Valid header but zero variant records should exit non-zero."""
        p = write_tmp(HEADER_ONLY)
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_non_vcf_text_file_exits_nonzero(self):
        """Plain text file with no VCF structure should exit non-zero."""
        p = write_tmp(NON_VCF_CONTENT, suffix=".txt")
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_23andme_file_exits_nonzero(self):
        """23andMe genotype file should NOT be silently parsed as a VCF."""
        p = write_tmp(TWENTY_THREE_AND_ME_LIKE, suffix=".txt")
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0

    def test_zero_byte_file_exits_nonzero(self):
        """Zero-byte file should exit non-zero."""
        with tempfile.NamedTemporaryFile(suffix=".vcf", delete=False) as f:
            p = Path(f.name)
        with pytest.raises(SystemExit) as exc:
            parse_vcf(p)
        assert exc.value.code != 0


# ── Tests: valid input should parse correctly ──────────────────────────────────

class TestValidVCFParsesCorrectly:

    def test_valid_vcf_returns_variants(self):
        p = write_tmp(VALID_VCF)
        variants = parse_vcf(p)
        assert len(variants) == 2

    def test_valid_vcf_strips_chr_prefix(self):
        vcf = VALID_VCF.replace("17\t", "chr17\t")
        p = write_tmp(vcf)
        variants = parse_vcf(p)
        assert variants[0]["chrom"] == "17"

    def test_valid_vcf_dot_id_becomes_empty(self):
        p = write_tmp(VALID_VCF)
        variants = parse_vcf(p)
        # rs IDs should be preserved
        assert variants[0]["id"] == "rs80357382"

    def test_valid_vcf_required_fields(self):
        p = write_tmp(VALID_VCF)
        variants = parse_vcf(p)
        for v in variants:
            assert "chrom" in v
            assert "pos" in v
            assert "ref" in v
            assert "alt" in v
